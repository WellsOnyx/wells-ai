'use client'

import { useState, useRef, useEffect } from 'react'
import {
  X,
  Send,
  Sparkles,
  Paperclip,
  Minimize2,
  Maximize2,
  Clock,
  ChevronDown,
  Loader2,
  AtSign,
  Bold,
  Italic,
  Underline,
  List,
  Link as LinkIcon
} from 'lucide-react'

interface ComposeModalProps {
  isOpen: boolean
  onClose: () => void
  onSend: (data: {
    to: string[]
    cc?: string[]
    bcc?: string[]
    subject: string
    body: string
    account?: string
    scheduledFor?: Date
  }) => Promise<void>
  accounts?: Array<{ id: string; email: string; provider: string }>
  defaultTo?: string
  defaultSubject?: string
}

export default function ComposeModal({
  isOpen,
  onClose,
  onSend,
  accounts = [],
  defaultTo = '',
  defaultSubject = ''
}: ComposeModalProps) {
  const [to, setTo] = useState(defaultTo)
  const [cc, setCc] = useState('')
  const [bcc, setBcc] = useState('')
  const [subject, setSubject] = useState(defaultSubject)
  const [body, setBody] = useState('')
  const [showCc, setShowCc] = useState(false)
  const [showBcc, setShowBcc] = useState(false)
  const [isMinimized, setIsMinimized] = useState(false)
  const [isScheduling, setIsScheduling] = useState(false)
  const [selectedAccount, setSelectedAccount] = useState(accounts[0]?.id || '')
  const [isSending, setIsSending] = useState(false)
  const [isGeneratingAI, setIsGeneratingAI] = useState(false)
  const [showAccountPicker, setShowAccountPicker] = useState(false)

  const bodyRef = useRef<HTMLTextAreaElement>(null)

  useEffect(() => {
    if (isOpen && !isMinimized) {
      // Focus body after a brief delay
      setTimeout(() => bodyRef.current?.focus(), 100)
    }
  }, [isOpen, isMinimized])

  useEffect(() => {
    setTo(defaultTo)
    setSubject(defaultSubject)
  }, [defaultTo, defaultSubject])

  const handleSend = async () => {
    if (!to.trim() || !subject.trim()) return

    setIsSending(true)
    try {
      await onSend({
        to: to.split(',').map(e => e.trim()).filter(Boolean),
        cc: cc ? cc.split(',').map(e => e.trim()).filter(Boolean) : undefined,
        bcc: bcc ? bcc.split(',').map(e => e.trim()).filter(Boolean) : undefined,
        subject,
        body,
        account: selectedAccount
      })
      // Reset form
      setTo('')
      setCc('')
      setBcc('')
      setSubject('')
      setBody('')
      setShowCc(false)
      setShowBcc(false)
      onClose()
    } catch (error) {
      console.error('Failed to send:', error)
    } finally {
      setIsSending(false)
    }
  }

  const handleAIWrite = async () => {
    setIsGeneratingAI(true)
    try {
      // TODO: Integrate with AI writing assistant
      const aiContent = `AI-generated content based on subject: ${subject}\n\n[This would be generated by your AI model]`
      setBody(body + '\n\n' + aiContent)
    } catch (error) {
      console.error('Failed to generate AI content:', error)
    } finally {
      setIsGeneratingAI(false)
    }
  }

  const selectedAccountData = accounts.find(a => a.id === selectedAccount)

  if (!isOpen) return null

  if (isMinimized) {
    return (
      <div className="fixed bottom-0 right-6 w-80 bg-black/95 backdrop-blur-xl border border-white/10 rounded-t-xl shadow-2xl z-50">
        <div className="p-3 flex items-center justify-between cursor-pointer" onClick={() => setIsMinimized(false)}>
          <div className="flex items-center gap-2">
            <div className="w-2 h-2 rounded-full bg-amber-500 animate-pulse" />
            <span className="text-sm text-white font-medium truncate">
              {subject || 'New Message'}
            </span>
          </div>
          <div className="flex items-center gap-1">
            <button
              onClick={(e) => {
                e.stopPropagation()
                setIsMinimized(false)
              }}
              className="p-1 hover:bg-white/10 rounded transition-colors"
            >
              <Maximize2 className="w-4 h-4 text-gray-400" />
            </button>
            <button
              onClick={(e) => {
                e.stopPropagation()
                onClose()
              }}
              className="p-1 hover:bg-white/10 rounded transition-colors"
            >
              <X className="w-4 h-4 text-gray-400" />
            </button>
          </div>
        </div>
      </div>
    )
  }

  return (
    <>
      {/* Backdrop */}
      <div
        className="fixed inset-0 bg-black/60 backdrop-blur-sm z-40 animate-in fade-in duration-200"
        onClick={onClose}
      />

      {/* Modal */}
      <div className="fixed inset-0 flex items-center justify-center z-50 p-4 pointer-events-none">
        <div
          className="w-full max-w-3xl bg-black/95 backdrop-blur-xl border border-white/10 rounded-2xl shadow-2xl overflow-hidden pointer-events-auto animate-in zoom-in-95 duration-200"
          onClick={(e) => e.stopPropagation()}
        >
          {/* Header */}
          <div className="flex items-center justify-between px-6 py-4 border-b border-white/10">
            <h2 className="text-lg font-semibold text-white">New Message</h2>
            <div className="flex items-center gap-2">
              <button
                onClick={() => setIsMinimized(true)}
                className="p-2 hover:bg-white/10 rounded-lg transition-colors"
                title="Minimize"
              >
                <Minimize2 className="w-4 h-4 text-gray-400" />
              </button>
              <button
                onClick={onClose}
                className="p-2 hover:bg-white/10 rounded-lg transition-colors"
                title="Close"
              >
                <X className="w-4 h-4 text-gray-400" />
              </button>
            </div>
          </div>

          {/* From Account Selector */}
          {accounts.length > 0 && (
            <div className="px-6 py-3 border-b border-white/5 flex items-center gap-3">
              <label className="text-sm text-gray-500 w-16">From:</label>
              <div className="relative flex-1">
                <button
                  onClick={() => setShowAccountPicker(!showAccountPicker)}
                  className="flex items-center gap-2 px-3 py-2 rounded-lg bg-white/5 hover:bg-white/10 border border-white/10 hover:border-white/20 transition-all text-sm text-white w-full"
                >
                  <AtSign className="w-4 h-4 text-gray-400" />
                  <span className="flex-1 text-left">
                    {selectedAccountData?.email || 'Select account'}
                  </span>
                  <ChevronDown className="w-4 h-4 text-gray-400" />
                </button>

                {showAccountPicker && (
                  <div className="absolute top-full mt-2 w-full bg-black/95 backdrop-blur-xl border border-white/10 rounded-xl shadow-xl z-10 overflow-hidden">
                    {accounts.map((account) => (
                      <button
                        key={account.id}
                        onClick={() => {
                          setSelectedAccount(account.id)
                          setShowAccountPicker(false)
                        }}
                        className="w-full px-4 py-2.5 text-left hover:bg-white/10 transition-colors flex items-center gap-2 text-sm"
                      >
                        <AtSign className="w-4 h-4 text-gray-400" />
                        <span className="text-white">{account.email}</span>
                        <span className="text-gray-500 text-xs ml-auto">{account.provider}</span>
                      </button>
                    ))}
                  </div>
                )}
              </div>
            </div>
          )}

          {/* To Field */}
          <div className="px-6 py-3 border-b border-white/5 flex items-center gap-3">
            <label className="text-sm text-gray-500 w-16">To:</label>
            <input
              type="text"
              value={to}
              onChange={(e) => setTo(e.target.value)}
              placeholder="recipient@example.com"
              className="flex-1 bg-transparent text-white placeholder:text-gray-600 outline-none text-sm"
            />
            <div className="flex items-center gap-2">
              {!showCc && (
                <button
                  onClick={() => setShowCc(true)}
                  className="text-xs text-gray-500 hover:text-gray-300 transition-colors px-2 py-1"
                >
                  Cc
                </button>
              )}
              {!showBcc && (
                <button
                  onClick={() => setShowBcc(true)}
                  className="text-xs text-gray-500 hover:text-gray-300 transition-colors px-2 py-1"
                >
                  Bcc
                </button>
              )}
            </div>
          </div>

          {/* Cc Field */}
          {showCc && (
            <div className="px-6 py-3 border-b border-white/5 flex items-center gap-3">
              <label className="text-sm text-gray-500 w-16">Cc:</label>
              <input
                type="text"
                value={cc}
                onChange={(e) => setCc(e.target.value)}
                placeholder="cc@example.com"
                className="flex-1 bg-transparent text-white placeholder:text-gray-600 outline-none text-sm"
              />
              <button
                onClick={() => {
                  setShowCc(false)
                  setCc('')
                }}
                className="p-1 hover:bg-white/10 rounded transition-colors"
              >
                <X className="w-3 h-3 text-gray-500" />
              </button>
            </div>
          )}

          {/* Bcc Field */}
          {showBcc && (
            <div className="px-6 py-3 border-b border-white/5 flex items-center gap-3">
              <label className="text-sm text-gray-500 w-16">Bcc:</label>
              <input
                type="text"
                value={bcc}
                onChange={(e) => setBcc(e.target.value)}
                placeholder="bcc@example.com"
                className="flex-1 bg-transparent text-white placeholder:text-gray-600 outline-none text-sm"
              />
              <button
                onClick={() => {
                  setShowBcc(false)
                  setBcc('')
                }}
                className="p-1 hover:bg-white/10 rounded transition-colors"
              >
                <X className="w-3 h-3 text-gray-500" />
              </button>
            </div>
          )}

          {/* Subject Field */}
          <div className="px-6 py-3 border-b border-white/5 flex items-center gap-3">
            <label className="text-sm text-gray-500 w-16">Subject:</label>
            <input
              type="text"
              value={subject}
              onChange={(e) => setSubject(e.target.value)}
              placeholder="Email subject"
              className="flex-1 bg-transparent text-white placeholder:text-gray-600 outline-none text-sm font-medium"
            />
          </div>

          {/* Body */}
          <div className="px-6 py-4 min-h-[300px]">
            <textarea
              ref={bodyRef}
              value={body}
              onChange={(e) => setBody(e.target.value)}
              placeholder="Type your message here..."
              className="w-full h-[300px] bg-transparent text-white placeholder:text-gray-600 outline-none resize-none text-sm leading-relaxed"
            />
          </div>

          {/* Footer */}
          <div className="px-6 py-4 border-t border-white/10 flex items-center justify-between">
            <div className="flex items-center gap-2">
              <button
                onClick={handleAIWrite}
                disabled={isGeneratingAI}
                aria-label="Generate text with AI"
                className="px-4 py-2 rounded-lg bg-purple-500/20 text-purple-400 border border-purple-500/30 transition-all duration-200 hover:bg-purple-500/30 hover:border-purple-500/50 focus:outline-none focus-visible:ring-2 focus-visible:ring-purple-500 disabled:opacity-50 disabled:cursor-not-allowed active:scale-[0.98] flex items-center gap-2 text-sm font-medium"
              >
                {isGeneratingAI ? (
                  <Loader2 className="w-4 h-4 animate-spin" aria-hidden="true" />
                ) : (
                  <Sparkles className="w-4 h-4" aria-hidden="true" />
                )}
                AI Write
              </button>

              <button
                className="p-2 rounded-lg transition-all duration-200 hover:bg-white/10 focus:outline-none focus-visible:ring-2 focus-visible:ring-white/30"
                title="Attach files"
                aria-label="Attach files"
              >
                <Paperclip className="w-4 h-4 text-gray-400" aria-hidden="true" />
              </button>

              <button
                onClick={() => setIsScheduling(!isScheduling)}
                className="p-2 rounded-lg transition-all duration-200 hover:bg-white/10 focus:outline-none focus-visible:ring-2 focus-visible:ring-white/30"
                title="Schedule send"
                aria-label="Schedule send"
                aria-expanded={isScheduling}
              >
                <Clock className="w-4 h-4 text-gray-400" aria-hidden="true" />
              </button>
            </div>

            <div className="flex items-center gap-3">
              <button
                onClick={onClose}
                className="px-4 py-2 text-gray-400 transition-all duration-200 hover:text-white hover:bg-white/5 rounded-lg text-sm font-medium focus:outline-none focus-visible:ring-2 focus-visible:ring-white/30"
              >
                Cancel
              </button>
              <button
                onClick={handleSend}
                disabled={!to.trim() || !subject.trim() || isSending}
                aria-label="Send email"
                className="px-6 py-2 rounded-lg bg-amber-500 text-black font-semibold transition-all duration-200 hover:bg-amber-400 hover:shadow-lg hover:shadow-amber-500/25 focus:outline-none focus-visible:ring-2 focus-visible:ring-amber-500 focus-visible:ring-offset-2 focus-visible:ring-offset-black disabled:opacity-50 disabled:cursor-not-allowed disabled:hover:shadow-none active:scale-[0.98] flex items-center gap-2"
              >
                {isSending ? (
                  <Loader2 className="w-4 h-4 animate-spin" aria-hidden="true" />
                ) : (
                  <Send className="w-4 h-4" aria-hidden="true" />
                )}
                Send
              </button>
            </div>
          </div>

          {/* Schedule Picker */}
          {isScheduling && (
            <div className="px-6 py-4 border-t border-white/10 bg-white/5 animate-in slide-in-from-top-2 duration-200">
              <div className="text-sm text-gray-400 mb-3">Schedule send for:</div>
              <div className="grid grid-cols-3 gap-2" role="group" aria-label="Schedule options">
                {[
                  { label: 'Later today (6pm)', value: 'today_6pm' },
                  { label: 'Tomorrow (9am)', value: 'tomorrow_9am' },
                  { label: 'Monday (9am)', value: 'monday_9am' }
                ].map((option) => (
                  <button
                    key={option.value}
                    className="px-4 py-2.5 rounded-lg bg-white/5 border border-white/10 text-sm text-white transition-all duration-200 hover:bg-white/10 hover:border-amber-500/50 focus:outline-none focus-visible:ring-2 focus-visible:ring-amber-500 active:scale-[0.98]"
                  >
                    {option.label}
                  </button>
                ))}
              </div>
            </div>
          )}
        </div>
      </div>
    </>
  )
}
