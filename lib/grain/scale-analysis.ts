// SELLER DASHBOARD WITH MULTI-CURRENCY
// ============================================================================

export interface GlobalSellerDashboard {
  // Core balance
  grainBalance: number

  // Display in preferred currency
  preferredCurrency: string
  localEquivalent: number

  // Cash out value (always USD)
  cashOutValueUsd: number

  // Revenue by currency (shows where sales came from)
  revenueBySourceCurrency: Record<string, number>

  // Expenses by destination currency
  expensesByDestCurrency: Record<string, number>

  // FX savings
  fxFeesSaved: number  // What they would have paid in FX fees
}

export function calculateGlobalSellerDashboard(
  grainBalance: number,
  preferredCurrency: string,
  transactions: Array<{
    type: 'incoming' | 'outgoing'
    amount: number
    counterpartyCurrency: string
  }>
): GlobalSellerDashboard {
  const localEquivalent = displayInLocalCurrency(grainBalance, preferredCurrency).localAmount

  // Group revenue by source currency
  const revenueBySourceCurrency: Record<string, number> = {}
  const expensesByDestCurrency: Record<string, number> = {}
  let fxFeesSaved = 0

  for (const tx of transactions) {
    if (tx.type === 'incoming') {
      revenueBySourceCurrency[tx.counterpartyCurrency] =
        (revenueBySourceCurrency[tx.counterpartyCurrency] || 0) + tx.amount

      // Would have paid ~2% FX fee on cross-currency
      if (tx.counterpartyCurrency !== preferredCurrency) {
        fxFeesSaved += tx.amount * 0.02
      }
    } else {
      expensesByDestCurrency[tx.counterpartyCurrency] =
        (expensesByDestCurrency[tx.counterpartyCurrency] || 0) + tx.amount

      if (tx.counterpartyCurrency !== preferredCurrency) {
        fxFeesSaved += tx.amount * 0.02
      }
    }
  }

  return {
    grainBalance,
    preferredCurrency,
    localEquivalent,
    cashOutValueUsd: grainBalance, // Always 1:1
    revenueBySourceCurrency,
    expensesByDestCurrency,
    fxFeesSaved
  }
}

