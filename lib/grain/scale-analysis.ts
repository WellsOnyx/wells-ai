export interface ScaleProjection {
  grainSupply: number           // Total GRAIN in circulation
  annualVolume: number          // Transaction volume
  userCount: number
  feesSavedAnnually: number
  platformRevenue: number
  platformCosts: number
  platformProfit: number
  perUserSavings: number
}

export function projectAtScale(grainSupply: number): ScaleProjection {
  // Velocity: assume 4x/year (PayPal-like)
  const velocityRate = 4
  const annualVolume = grainSupply * velocityRate

  // User estimates (assume $20k average balance per user)
  const avgBalancePerUser = 20000
  const userCount = grainSupply / avgBalancePerUser

  // Fee savings calculation
  const cardProcessingRate = 0.025  // 2.5% average
  const wireFeesPerTx = 15
  const payrollFeePerTx = 7.5
  const fxFeeRate = 0.02  // 2% on international

  // Estimate transaction mix
  const cardVolume = annualVolume * 0.6   // 60% would be card payments
  const wireVolume = annualVolume * 0.2   // 20% would be wire/ACH
  const payrollVolume = annualVolume * 0.1 // 10% would be payroll
  const fxVolume = annualVolume * 0.3     // 30% would involve FX

  const cardFeesSaved = cardVolume * cardProcessingRate
  const wireFeesSaved = (wireVolume / 1000) * wireFeesPerTx // ~1 wire per $1k
  const payrollFeesSaved = (payrollVolume / 5000) * payrollFeePerTx // ~1 payroll per $5k
  const fxFeesSaved = fxVolume * fxFeeRate

  const feesSavedAnnually = cardFeesSaved + wireFeesSaved + payrollFeesSaved + fxFeesSaved

  // Platform economics
  const treasuryYield = 0.03  // 3% conservative yield
  const platformRevenue = grainSupply * treasuryYield

  // Costs scale sub-linearly
  const baseCosts = 100_000_000  // $100M base
  const variableCostRate = 0.0005  // 0.05% of supply
  const platformCosts = baseCosts + (grainSupply * variableCostRate)

  const platformProfit = platformRevenue - platformCosts
  const perUserSavings = feesSavedAnnually / userCount

  return {
    grainSupply,
    annualVolume,
    userCount,
    feesSavedAnnually,
    platformRevenue,
    platformCosts,
    platformProfit,
    perUserSavings
  }
}

