export interface CurrencyDisplay {
  grainAmount: number
  localCurrency: string
  localAmount: number
  exchangeRate: number
}

// Common exchange rates (would be real-time in production)
const FX_RATES: Record<string, number> = {
  USD: 1.00,
  EUR: 0.92,
  GBP: 0.79,
  JPY: 149.50,
  CAD: 1.36,
  AUD: 1.53,
  MXN: 17.15,
  BRL: 4.97,
  INR: 83.12,
  CNY: 7.24,
  // ... 180+ currencies via Circle
}

export function displayInLocalCurrency(
  grainAmount: number,
  currency: string
): CurrencyDisplay {
  const rate = FX_RATES[currency] || 1
  const localAmount = grainAmount * rate

  return {
    grainAmount,
    localCurrency: currency,
    localAmount,
    exchangeRate: rate
  }
}

export function formatForDashboard(
  grainAmount: number,
  preferredCurrency: string
): {
  grain: string
  local: string
  cashOut: string
} {
  const display = displayInLocalCurrency(grainAmount, preferredCurrency)

  return {
    grain: `${grainAmount.toLocaleString()} GRAIN`,
    local: `≈ ${display.localAmount.toLocaleString(undefined, {
      style: 'currency',
      currency: preferredCurrency
    })}`,
    cashOut: `$${grainAmount.toLocaleString()} USD` // Cash out always in USD
  }
}

