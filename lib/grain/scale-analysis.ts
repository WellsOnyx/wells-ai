// ============================================================================

export interface NetworkHealth {
  // Circulation metrics
  totalSupply: number
  activeCirculation: number    // Moved in last 30 days
  circulationRate: number      // activeCirculation / totalSupply

  // User metrics
  totalUsers: number
  activeUsers: number          // Transacted in last 30 days
  userActivityRate: number

  // Transaction metrics
  dailyVolume: number
  dailyTransactions: number
  avgTransactionSize: number

  // Retention metrics
  depositRetentionRate: number  // % of deposits still in network
  avgHoldingPeriod: number      // Days before cash-out

  // Health scores (0-100)
  velocityScore: number         // Higher is better
  retentionScore: number        // Higher is better
  networkScore: number          // Combined health
}

export function assessNetworkHealth(metrics: {
  totalSupply: number
  volumeLast30Days: number
  transactionsLast30Days: number
  activeUsersLast30Days: number
  totalUsers: number
  cashOutLast30Days: number
  depositsAllTime: number
}): NetworkHealth {
  const circulationRate = metrics.volumeLast30Days / metrics.totalSupply
  const userActivityRate = metrics.activeUsersLast30Days / metrics.totalUsers
  const avgTransactionSize = metrics.volumeLast30Days / metrics.transactionsLast30Days
  const dailyVolume = metrics.volumeLast30Days / 30
  const dailyTransactions = metrics.transactionsLast30Days / 30

  // Retention: how much of all-time deposits are still in the network
  // (This is a simplified calculation)
  const depositRetentionRate = metrics.totalSupply / metrics.depositsAllTime

  // Health scores
  const velocityScore = Math.min(100, circulationRate * 25) // 4x velocity = 100
  const retentionScore = depositRetentionRate * 100
  const networkScore = (velocityScore * 0.4) + (retentionScore * 0.4) + (userActivityRate * 100 * 0.2)

  return {
    totalSupply: metrics.totalSupply,
    activeCirculation: metrics.volumeLast30Days,
    circulationRate,
    totalUsers: metrics.totalUsers,
    activeUsers: metrics.activeUsersLast30Days,
    userActivityRate,
    dailyVolume,
    dailyTransactions,
    avgTransactionSize,
    depositRetentionRate,
    avgHoldingPeriod: 0, // Would need historical data
    velocityScore,
    retentionScore,
    networkScore
  }
}

